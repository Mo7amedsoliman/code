import type { Metadata } from "next";
import localFont from "next/font/local";
import "./globals.css";
import Providers from "./providers";
import { Toaster } from "sonner";
import Footer from "@/components/shared/Footer/Footer";
import Navbar from "@/components/shared/Navbar/Navbar";
import { VerifyToken } from "@/features/auth/services/auth.actions";
import { getCartItems } from "@/features/cart/server/cart.actions";
import { CartValueType } from "@/features/cart/slices/cart.slice";
import { getWishlist } from "@/features/wishlist/server/wishlist.actions";
import { WishlistValueType } from "@/features/wishlist/slices/wishlist.slice";
import { getAllCategories } from "@/features/categories/services/gitAllCategories";
import { Category } from "@/features/categories/types/categories.types";
const geistSans = localFont({
  src: "../assets/fonts/geist-latin.woff2",
  variable: "--font-geist-sans",
  weight: "400 600",
  display: "swap",
});

const geistMono = localFont({
  src: "../assets/fonts/geist-mono-latin.woff2",
  variable: "--font-geist-mono",
  weight: "400 600",
  display: "swap",
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const authStates = await VerifyToken();
  const categoriesResponse = await getAllCategories().catch(() => null);
  const categories: Category[] = categoriesResponse?.data ?? [];
  let cartvalues: CartValueType = {
    status: "",
    message: "",
    numOfCartItems: 0,
    cartId: null,
    data: {
      products: [],
      totalCartPrice: 0,
    },
  };
  let wishlistValues: WishlistValueType = {
    status: authStates.isAuthenticated ? "" : "fail",
    message: authStates.isAuthenticated
      ? ""
      : "Please log in to access your wishlist.",
    count: 0,
    data: [],
  };
  if (authStates.isAuthenticated === true) {
    const cartResponse = await getCartItems();
    if (cartResponse.status === "success") {
      cartvalues = cartResponse;
    }

    const wishlistResponse = await getWishlist();
    if (wishlistResponse.status === "success") {
      wishlistValues = {
        status: wishlistResponse.status,
        message: wishlistResponse.message ?? "",
        count: wishlistResponse.count ?? wishlistResponse.data.length,
        data: wishlistResponse.data,
      };
    }

    console.log(authStates);
  }

  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full ">
        <Providers
          preloadState={{
            AuthReducer: authStates,
            cartReducer: cartvalues,
            wishlistReducer: wishlistValues,
          }}
        >
          <Navbar categories={categories} />
          {children}
          <Footer />

          <Toaster richColors position="bottom-right" />
        </Providers>
      </body>
    </html>
  );
}
